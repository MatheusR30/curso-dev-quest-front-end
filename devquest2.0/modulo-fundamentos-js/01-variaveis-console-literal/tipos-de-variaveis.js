// A diferença entre var e let é que var tem escopo global ou de função,
// enquanto let tem escopo de bloco. Isso significa que uma variável declarada
//  com var pode ser acessada em qualquer lugar do código, enquanto uma variável
//  declarada com let só pode ser acessada dentro do bloco onde foi declarada.
let nome = "Matheus";
nome = "João";

